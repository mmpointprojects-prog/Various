// Prints seed SQL for the Supabase tables from the venue files in src/data/venues.
// Usage: npm run seed:sql   (writes supabase/seed.sql)
import { VENUES } from '../src/data/venues/index.ts';
import { ringsOf } from '../src/lib/geometry.ts';

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a: (string | number)[], type: string) => `array[${a.map((x) => (typeof x === 'number' ? x : q(x))).join(',')}]::${type}[]`;

const out: string[] = ['-- Generated by scripts/export-seed.ts. Do not edit by hand.', 'begin;'];
for (const v of VENUES) {
  out.push(`insert into public.venues (id,name,city,state,ceiling_ft,seat_colors,model_notes,sources) values (${q(v.id)},${q(v.name)},${q(v.city)},${q(v.state)},${v.ceiling},${arr(v.seatColors, 'integer')},${q(v.modelNotes)},${j(v.sources)}) on conflict (id) do update set name=excluded.name, city=excluded.city, ceiling_ft=excluded.ceiling_ft, seat_colors=excluded.seat_colors, model_notes=excluded.model_notes, sources=excluded.sources;`);
  for (const L of ringsOf(v.levels)) {
    out.push(`insert into public.levels values (${q(v.id)},${q(L.key)},${q(L.name)},${L.rx0},${L.rx1},${L.rz0},${L.rz1},${L.n},${L.rows},${L.y0},${L.rise},${L.count},${L.first},${L.centerNum},${q(L.prefix ?? '')}) on conflict (venue_id, level_key) do update set name=excluded.name, rx0=excluded.rx0, rx1=excluded.rx1, rz0=excluded.rz0, rz1=excluded.rz1, n=excluded.n, row_count=excluded.row_count, y0=excluded.y0, rise=excluded.rise, section_count=excluded.section_count, first_section=excluded.first_section, center_num=excluded.center_num, section_prefix=excluded.section_prefix;`);
  }
  for (const s of Object.values(v.setups)) {
    if (!s) continue;
    out.push(`insert into public.setups values (${q(v.id)},${q(s.id)},${q(s.label)},${q(s.sport ?? null)},${arr(s.closed, 'text')},${j(s.target)},${s.front ? j(s.front) : 'null'},${q(s.note)},${s.priceScale ?? 1},${j(v.defaults[s.id] ?? [])}) on conflict (venue_id, setup_id) do nothing;`);
    for (const f of s.floor) {
      out.push(`insert into public.floor_sections values (${q(v.id)},${q(s.id)},${q(f.id)},${q(f.label)},${q(f.short)},${f.x0},${f.x1},${f.z0},${f.z1},${q(f.front)},${f.rows},${!!f.seated},${!!f.courtside}) on conflict do nothing;`);
    }
  }
  for (const e of v.events) {
    out.push(`insert into public.events (id,venue_id,event_date,event_time,title,event_type,setup_id,confirmed) values (${q(e.id)},${q(v.id)},${q(e.date)},${q(e.time)},${q(e.title)},${q(e.type)},${q(e.setup)},${e.confirmed}) on conflict (id) do update set event_date=excluded.event_date, event_time=excluded.event_time, title=excluded.title, confirmed=excluded.confirmed, updated_at=now();`);
  }
}
out.push('commit;');
console.log(out.join('\n'));
