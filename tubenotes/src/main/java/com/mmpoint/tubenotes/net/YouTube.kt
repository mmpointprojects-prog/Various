package com.mmpoint.tubenotes.net

import com.mmpoint.tubenotes.data.Segment
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonObject
import java.net.URLEncoder

class YouTubeException(message: String) : Exception(message)

data class VideoInfo(val title: String, val channel: String)

data class FetchedTranscript(val title: String, val channel: String, val language: String, val segments: List<Segment>)

data class CaptionTrack(val baseUrl: String, val languageCode: String, val autoGenerated: Boolean)

/** Finds a video in a shared link and reads its captions the same way the YouTube app does. */
object YouTube {
    private val json = Json { ignoreUnknownKeys = true }
    private const val CLIENT_VERSION = "20.10.38"
    private const val USER_AGENT = "com.google.android.youtube/$CLIENT_VERSION (Linux; U; Android 14)"

    private val idPatterns = listOf(
        Regex("""(?:youtube\.com|youtube-nocookie\.com)/(?:watch\?(?:[^\s#]*&)?v=|shorts/|live/|embed/|v/)([A-Za-z0-9_-]{11})"""),
        Regex("""youtu\.be/([A-Za-z0-9_-]{11})"""),
    )

    /** Pulls the 11-character video id out of whatever text was shared (a bare id also works). */
    fun extractVideoId(text: String): String? {
        val t = text.trim()
        for (p in idPatterns) p.find(t)?.let { return it.groupValues[1] }
        return if (Regex("[A-Za-z0-9_-]{11}").matches(t)) t else null
    }

    fun watchUrl(videoId: String) = "https://www.youtube.com/watch?v=$videoId"

    /** Title and channel from YouTube's public oEmbed endpoint; null if unavailable. */
    fun fetchInfo(videoId: String): VideoInfo? = runCatching {
        val url = "https://www.youtube.com/oembed?format=json&url=" + URLEncoder.encode(watchUrl(videoId), "UTF-8")
        val r = Http.request(url)
        if (r.code != 200) return null
        val o = json.parseToJsonElement(r.body).jsonObject
        VideoInfo(o.str("title").orEmpty(), o.str("author_name").orEmpty())
    }.getOrNull()

    fun fetchTranscript(videoId: String, preferredLanguage: String = "en"): FetchedTranscript {
        val body = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "ANDROID")
                    put("clientVersion", CLIENT_VERSION)
                    put("androidSdkVersion", 34)
                    put("hl", preferredLanguage)
                }
            }
            put("videoId", videoId)
        }.toString()
        val r = Http.request(
            "https://www.youtube.com/youtubei/v1/player?prettyPrint=false",
            method = "POST",
            headers = mapOf("Content-Type" to "application/json", "User-Agent" to USER_AGENT),
            body = body,
        )
        if (r.code != 200) throw YouTubeException("YouTube answered with error ${r.code}. Try again later, or paste the transcript yourself.")
        val player = json.parseToJsonElement(r.body).jsonObject
        val status = player.obj("playabilityStatus")
        val state = status?.str("status")
        if (state != null && state != "OK") {
            val reason = status.str("reason") ?: state
            throw YouTubeException("YouTube didn't share this video's captions ($reason). You can paste the transcript yourself instead.")
        }
        val details = player.obj("videoDetails")
        val tracks = parseTracks(player)
        if (tracks.isEmpty()) throw YouTubeException("This video has no captions, so there is no transcript to read.")
        val track = pickTrack(tracks, preferredLanguage)
        val xml = Http.request(track.baseUrl.replace("&fmt=srv3", ""), headers = mapOf("User-Agent" to USER_AGENT))
        if (xml.code != 200) throw YouTubeException("Couldn't download the captions (error ${xml.code}). Try again, or paste the transcript yourself.")
        val segments = parseTimedText(xml.body)
        if (segments.isEmpty()) throw YouTubeException("The captions came back empty. Try again, or paste the transcript yourself.")
        return FetchedTranscript(
            title = details?.str("title").orEmpty(),
            channel = details?.str("author").orEmpty(),
            language = track.languageCode + if (track.autoGenerated) " (auto)" else "",
            segments = segments,
        )
    }

    fun parseTracks(player: JsonObject): List<CaptionTrack> {
        val list = player.obj("captions")?.obj("playerCaptionsTracklistRenderer")?.get("captionTracks") as? JsonArray
            ?: return emptyList()
        return list.mapNotNull { el ->
            val o = el.jsonObject
            val url = o.str("baseUrl") ?: return@mapNotNull null
            CaptionTrack(url, o.str("languageCode").orEmpty(), o.str("kind") == "asr")
        }
    }

    /** Preferred language written by a person, then auto-generated, then any human track, then anything. */
    fun pickTrack(tracks: List<CaptionTrack>, preferred: String): CaptionTrack {
        fun lang(t: CaptionTrack) = t.languageCode.substringBefore('-').lowercase()
        val p = preferred.substringBefore('-').lowercase()
        return tracks.firstOrNull { lang(it) == p && !it.autoGenerated }
            ?: tracks.firstOrNull { lang(it) == p }
            ?: tracks.firstOrNull { !it.autoGenerated }
            ?: tracks.first()
    }

    /** Reads both caption formats YouTube serves: `<text start dur>` (seconds) and srv3 `<p t d>` (ms). */
    fun parseTimedText(xml: String): List<Segment> {
        val out = mutableListOf<Segment>()
        Regex("""<text\b([^>]*)>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL).findAll(xml).forEach { m ->
            val start = attr(m.groupValues[1], "start")?.toDoubleOrNull() ?: 0.0
            clean(m.groupValues[2]).takeIf { it.isNotEmpty() }?.let { out += Segment(start, it) }
        }
        if (out.isNotEmpty()) return out
        Regex("""<p\b([^>]*)>(.*?)</p>""", RegexOption.DOT_MATCHES_ALL).findAll(xml).forEach { m ->
            val start = (attr(m.groupValues[1], "t")?.toDoubleOrNull() ?: 0.0) / 1000.0
            clean(m.groupValues[2]).takeIf { it.isNotEmpty() }?.let { out += Segment(start, it) }
        }
        return out
    }

    private fun attr(attrs: String, name: String) =
        Regex("""\b$name="([^"]*)"""").find(attrs)?.groupValues?.get(1)

    /** Strips inner tags and decodes entities (YouTube often double-escapes, e.g. `&amp;#39;`). */
    fun clean(raw: String): String {
        var s = raw.replace(Regex("<[^>]+>"), "")
        repeat(2) { s = decodeEntities(s) }
        return s.replace(Regex("\\s+"), " ").trim()
    }

    fun decodeEntities(s: String): String =
        Regex("&(#x[0-9a-fA-F]+|#[0-9]+|amp|lt|gt|quot|apos|nbsp);").replace(s) { m ->
            when (val e = m.groupValues[1]) {
                "amp" -> "&"
                "lt" -> "<"
                "gt" -> ">"
                "quot" -> "\""
                "apos" -> "'"
                "nbsp" -> " "
                else -> {
                    val code = if (e.startsWith("#x")) e.substring(2).toIntOrNull(16) else e.substring(1).toIntOrNull()
                    code?.let { String(Character.toChars(it)) } ?: m.value
                }
            }
        }

    private fun JsonObject.obj(key: String) = this[key] as? JsonObject
    private fun JsonObject.str(key: String) = (this[key] as? JsonPrimitive)?.contentOrNull
}
